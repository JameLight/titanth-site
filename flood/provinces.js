const LOOKUP = new Map(PROVINCES.map(name => [name, name]));

export function canonicalProvince(value) {
  let key = String(value ?? "").trim().replace(/\s+/g, "").replace(/ํา/g, "ำ").replace(/เเ/g, "แ");
  key = key.replace(/^(จังหวัด|จ\.)/, "");
  if (["กทม", "กทม.", "กรุงเทพ", "กรุงเทพฯ", "bangkok"].includes(key.toLowerCase())) key = "กรุงเทพมหานคร";
  return LOOKUP.get(key) ?? null;
}
